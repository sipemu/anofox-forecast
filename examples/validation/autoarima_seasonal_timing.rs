fn main() {
    let start = Utc.with_ymd_and_hms(1949, 1, 1, 0, 0, 0).unwrap();
    let times: Vec<_> = (0..Y.len())
        .map(|i| start + Duration::days(30 * i as i64))
        .collect();
    let series = TimeSeries::univariate(times, Y.to_vec()).unwrap();
    let reps = 5;
    let configs = [
        ("default (R rule: exact likelihood)", None),
        ("with_approximation(true)", Some(true)),
    ];
    for (label, approx) in configs {
        let mut best = f64::INFINITY;
        let mut name = String::new();
        for _ in 0..reps {
            let mut config = AutoARIMAConfig::default().with_seasonal_period(12);
            if let Some(a) = approx {
                config = config.with_approximation(a);
            }
            let mut model = AutoARIMA::with_config(config);
            let t = Instant::now();
            model.fit(&series).unwrap();
            best = best.min(t.elapsed().as_secs_f64());
            name = format!("{:?}", model.selected_full_order().unwrap());
        }
        println!("{label}: best of {reps} = {best:.3} s  -> {name}");
    }
}
